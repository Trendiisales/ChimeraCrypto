// ============================================================================
// veto_missed_bt.cpp — S-2026-07-12 missed-trades audit for the S54 200DMA
// macro veto (removed in 9f165c6, S-2026-07-11 BOUNCE RCA).
//
// QUESTION: what would the ACTIVE non-UPJUMP slot roster (24 TSMOM/ICHI
// engines, the "intermediate sleeve") have traded during the muzzled window
//   2026-05-31 03:00 UTC (S54j veto deploy, BTC already < 200d-MA)
//     -> 2026-07-11 11:00 UTC (9f165c6 fix deploy)
// had the veto not existed? During that entire window g_macro_bull was BEAR
// (journal: every [MACRO] line 74k spot vs 74-79k MA), so the veto blocked
// EVERY non-UPJUMP slot entry: the live baseline is exactly ZERO trades.
// The veto-off replay therefore IS the missed-trade delta.
//
// FAITHFULNESS:
//  * Runs the REAL production EdgeEngine.hpp (no reimplementation) with the
//    24 slot configs lifted VERBATIM from src/main.cpp (slot_configs.inc,
//    auto-generated by gen_slot_configs.py).
//  * Feed: Binance 1h klines as o,l,h,c ticks (adverse-low BEFORE favorable-
//    high — the S-2026-06-14 honest-fill convention from backtest_harness.cpp).
//    Engines aggregate to their native tf internally, exactly like live.
//  * Retained (non-veto) risk gates are modeled, since post-fix live still
//    applies them (this keeps the counterfactual honest, not a fantasy):
//      - per-symbol concurrency cap (1) + per-cluster cap (5), incl. occupancy
//        by the REAL live UPJUMP shadow positions (recovered closes)
//      - cluster 24h loss circuit-breaker (-150bp rolling)
//      - S54 chop-halt REGIME gate (BULL_TREND(3) required for trend kinds,
//        which all 24 are): global BTC regime + per-symbol regime, replicated
//        from main.cpp S34-r7/r8 logic. The 10-minute "short rally" return is
//        proxied from Binance 5m closes (live samples spot every 5s over a
//        120-sample = 10-min ring; 5m closes are the best offline proxy).
//        BTC D1/H4 trend + vol default BULLISH/1.0 live because no BTC TSMOM
//        D1/H4 slot is active — replicated. SOL/NEAR/SUI H4 trend and BNB D1
//        trend/vol are read from the replayed engines themselves, as live does.
//  * Costs: each engine's own round_trip_bp (20-22bp) via production net_bp.
//  * Convention: $10k notional per trade, 1bp = $1 (matches chimera_inbound).
//
// Modes:
//   ./veto_missed_bt              REGIME-GATED counterfactual (the honest one:
//                                 veto OFF, every other production gate ON)
//   ./veto_missed_bt --noregime   upper bound: regime chop-halt also OFF
//                                 (only concurrency + cluster-loss caps ON)
//
// Output: missed_trades_<mode>.csv + summary tables (full window + the
// Jul 8-11 bounce sub-window) to stdout.
//
// SHADOW throughout: live was shadow; "missed" = missed shadow/paper PnL.
// ============================================================================
